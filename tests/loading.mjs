import {chromium} from 'playwright';import assert from 'node:assert/strict';import fs from 'node:fs/promises';
const browser=await chromium.launch({executablePath:process.env.CHROMIUM_PATH||'/usr/bin/chromium',args:['--no-sandbox','--use-angle=swiftshader','--enable-unsafe-swiftshader']});
const url=process.env.TEST_URL||'http://127.0.0.1:4176';
try{
 const page=await browser.newPage({viewport:{width:1440,height:900}});page.setDefaultTimeout(120000);
 await page.addInitScript(()=>localStorage.setItem('apex-quality','low'));
 let release;const held=new Promise(r=>release=r);
 await page.route('**/models/car-concept.glb',async route=>{await held;await route.continue();});
 await page.goto(url,{waitUntil:'domcontentloaded'});
 assert.equal(await page.locator('#boot-screen').count(),1,'loading screen must exist before the launch screen');
 await page.locator('#boot-screen').waitFor({state:'visible'});
 assert.equal(await page.locator('main').evaluate(e=>e.inert),true);
 assert.equal(await page.locator('#drive').isDisabled(),true);
 await page.keyboard.press('w');assert.equal(await page.locator('body').evaluate(e=>e.classList.contains('driving')),false);
 assert.ok(Number(await page.locator('#boot-progress').getAttribute('aria-valuenow'))<100);
 await fs.mkdir('test-results',{recursive:true});await page.screenshot({path:'test-results/loading-desktop.png'});
 await page.setViewportSize({width:390,height:844});await page.screenshot({path:'test-results/loading-mobile.png'});
 assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),true);
 await page.setViewportSize({width:800,height:520});release();
 await page.locator('#boot-screen').waitFor({state:'hidden'});
 assert.equal(await page.locator('main').evaluate(e=>e.inert),false);
 assert.equal(await page.locator('#drive').isDisabled(),false);
 await page.keyboard.press('w');assert.equal(await page.locator('body').evaluate(e=>e.classList.contains('driving')),true);
 await page.close();
 const failure=await browser.newPage({viewport:{width:800,height:520}});failure.setDefaultTimeout(60000);await failure.emulateMedia({reducedMotion:'reduce'});
 let abort=true;await failure.route('**/models/car-concept.glb',route=>abort?route.abort():route.continue());
 await failure.goto(url,{waitUntil:'domcontentloaded'});
 await failure.waitForFunction(()=>document.querySelector('#boot-screen')?.dataset.state==='error');
 assert.equal(await failure.locator('#boot-retry').isVisible(),true);assert.equal(await failure.locator('main').evaluate(e=>e.inert),true);
 await failure.screenshot({path:'test-results/loading-error.png'});
 await failure.setViewportSize({width:568,height:320});
 await failure.locator('#boot-retry').scrollIntoViewIfNeeded();
 const retryBox=await failure.locator('#boot-retry').boundingBox();assert.ok(retryBox.y>=0&&retryBox.y+retryBox.height<=320,'retry remains reachable in short landscape');
 abort=false;
 await Promise.all([failure.waitForNavigation({waitUntil:'domcontentloaded'}),failure.locator('#boot-retry').click()]);
 assert.notEqual(await failure.locator('#boot-screen').getAttribute('data-state'),'error');
 await failure.locator('#boot-screen').waitFor({state:'hidden',timeout:120000});
 assert.equal(await failure.locator('#drive').isEnabled(),true);
 console.log('Loading screen passed: desktop/mobile, real loading gate, keyboard handoff, reduced motion and failure/retry.');
}finally{await browser.close();}
